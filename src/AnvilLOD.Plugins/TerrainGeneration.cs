public sealed record TerrainGenerationRequest(GameContextOptions Game, string OutputFolder,
    IReadOnlyCollection<string>? Worldspaces = null, IReadOnlyCollection<LodLevel>? Levels = null,
    int TextureSize = 512, float Brightness = 1, float VertexColorStrength = 1, float TextureRepeatsPerCell = 24,
    float SkirtDepth = 512, bool Water = true, bool UseExistingTerrain = true, bool ExportHeightmaps = true,
    int HeightmapMaximumSize = 8192, bool Seasons = false, TerrainMaterialSettings? Materials = null);
public sealed record TerrainTileResult(string Worldspace, int Level, int X, int Y, int Triangles, int WaterCells, string? Season = null);
public sealed record TerrainWorldResult(string Worldspace, int LandscapeCells, int ExistingTilesUsed, int Tiles, string? Heightmap);
public sealed record TerrainPerformance(int BuiltTiles, int ReusedTiles, IReadOnlyDictionary<string,double> Timings);
public sealed record TerrainGenerationResult(string OutputFolder, IReadOnlyList<TerrainWorldResult> Worlds,
    IReadOnlyList<TerrainTileResult> Tiles, IReadOnlyList<string> Warnings, double Seconds, string? PreviousOutput, OutputSnapshot Output,
    IReadOnlyList<TerrainMaterialReport>? Materials = null, TerrainPerformance? Performance = null);

public static class TerrainGeneration
{
    public const string ManifestName = "PenguLOD.terrain.json";
    public static void Validate(TerrainGenerationRequest r)
    {
        GenerationDestination.Validate(r.Game, r.OutputFolder);
        (r.Materials ?? new()).Validate();
        if(r.TextureSize is <64 or >2048 || (r.TextureSize&(r.TextureSize-1))!=0) throw new ArgumentException("Terrain texture size must be a power of two from 64 to 2048.");
        if(r.HeightmapMaximumSize is <128 or >16384 || (r.HeightmapMaximumSize&(r.HeightmapMaximumSize-1))!=0)throw new ArgumentException("Heightmap size limit must be a power of two from 128 to 16384.");
        if(!float.IsFinite(r.Brightness) || r.Brightness is <.1f or >4 || !float.IsFinite(r.VertexColorStrength) || r.VertexColorStrength is <0 or >1
            || !float.IsFinite(r.TextureRepeatsPerCell) || r.TextureRepeatsPerCell is <1 or >128 || !float.IsFinite(r.SkirtDepth) || r.SkirtDepth is <0 or >16384)
            throw new ArgumentException("Invalid terrain brightness, vertex colour, tiling or skirt setting.");
        if(r.Levels is { Count:0 } || r.Levels?.Any(l=>l is not (LodLevel.Lod4 or LodLevel.Lod8 or LodLevel.Lod16 or LodLevel.Lod32))==true)
            throw new ArgumentException("Terrain levels must be 4, 8, 16 or 32.");
        if(Directory.Exists(r.OutputFolder) && !File.Exists(Path.Combine(r.OutputFolder,ManifestName))
            && Directory.EnumerateFileSystemEntries(r.OutputFolder).Any(p=>!Path.GetFileName(p).Equals("meta.ini",StringComparison.OrdinalIgnoreCase)))
            throw new ArgumentException("Choose a new terrain output folder, or one previously generated by PenguLOD terrain generation.");
    }
    public static TerrainGenerationResult Run(TerrainGenerationRequest request,IProgress<string>? progress=null,CancellationToken ct=default)
        => RunCore(request,progress,ct,null);
    internal static TerrainGenerationResult RunWithCheckpoints(TerrainGenerationRequest request,string folder,string fingerprint,bool reuse,IProgress<string>? progress,CancellationToken ct)
        => RunCore(request,progress,ct,new TerrainTileCache(folder,fingerprint,reuse,progress,ct));
    private static TerrainGenerationResult RunCore(TerrainGenerationRequest request,IProgress<string>? progress,CancellationToken ct,TerrainTileCache? cache)
    {
        Validate(request);ct.ThrowIfCancellationRequested();var watch=Stopwatch.StartNew();
        using var limits=RunLimits.Enter(RunLimits.Parallel(ct).MaxDegreeOfParallelism,ct,RunLimits.CacheDirectory);
        using var preparation=WorkTiming.Measure("preparation");
        using var game=GameContext.Open(request.Game with{ExcludeFolder=request.OutputFolder,ExtraLooseRoots=["textures","meshes","lodsettings","seasons"]},progress);
        if(game.MissingPlugins.Count>0)throw new InvalidDataException("Resolve missing plugins before terrain generation: "+string.Join(", ",game.MissingPlugins.Take(5)));
        var assets=game.BuildAssets(p=>p.StartsWith("textures\\") || p.StartsWith("meshes\\terrain\\") || p.StartsWith("lodsettings\\") || p.StartsWith("seasons\\"));
        if(assets.SkippedArchives.Count>0)throw new InvalidDataException("Terrain generation cannot read required archives: "+string.Join(", ",assets.SkippedArchives));
        string defaultDiffuse = TerrainDefaultTexture.Resolve(request.Game, game.DataFolder);
        string defaultNormal = TerrainDefaultTexture.Resolve(request.Game, game.DataFolder, normal: true);
        progress?.Report("Default landscape diffuse: " + defaultDiffuse);
        var seasons = request.Seasons ? SeasonalAssets.Read(game,assets,"LandTextures") : new Dictionary<string,Dictionary<Mutagen.Bethesda.Plugins.FormKey,Mutagen.Bethesda.Plugins.FormKey>>();
        var wanted=request.Worldspaces is {Count:>0}?new HashSet<string>(request.Worldspaces,StringComparer.OrdinalIgnoreCase):null;
        var worlds=game.LoadOrder.PriorityOrder.Worldspace().WinningOverrides().Where(w=>!w.IsDeleted && w.EditorID is {} id && (wanted is null||wanted.Contains(id))).ToArray();
        var owned = new OutputSnapshot();
        var reports=new List<TerrainWorldResult>();var tiles=new List<TerrainTileResult>();var warnings=new List<string>(game.Warnings);
        var materialReports = new HashSet<TerrainMaterialReport>();
        var timings=new Dictionary<string,double>();int built=0,reused=0;
        void Warn(string s){warnings.Add(s);progress?.Report("WARNING: "+s);}
        using var stage=new StagedOutput(request.OutputFolder,false,progress,ct);
        preparation.Dispose();using var generation=WorkTiming.Measure("generation");
        foreach(var world in worlds)
        {
            ct.ThrowIfCancellationRequested();string name=world.EditorID!;
            if(!Regex.IsMatch(name,@"^[A-Za-z0-9_]+$"))throw new InvalidDataException("Unsupported worldspace EditorID: "+name);
            if(!assets.TryOpen(LodSettings.RelativePathFor(name),out var s)) {Warn(name+": no LOD settings; worldspace skipped.");continue;}
            LodSettings settings;using(s){var bytes=new byte[16];s.ReadExactly(bytes);settings=LodSettings.Parse(bytes);}
            if(settings.Stride is <4 or >4096 || (settings.Stride&(settings.Stride-1))!=0)throw new InvalidDataException(name+": invalid LOD grid bounds.");
            var levels=(request.Levels??new[]{LodLevel.Lod4,LodLevel.Lod8,LodLevel.Lod16,LodLevel.Lod32}).Where(settings.Supports).Distinct().ToArray();
            var grid=new LodGrid(name,settings);var source=new TerrainSource(game,assets,world,grid,request.UseExistingTerrain,ct,defaultDiffuse:defaultDiffuse,defaultNormal:defaultNormal,materials:request.Materials);
            var planned=source.Tiles(levels).ToArray();
            if(planned.Length==0){Warn(name+": no landscape or existing terrain in the selected grid/levels; skipped.");continue;}
            if(request.Water && !source.HasLodWater) Warn(name+": no worldspace LOD-water record; water meshes are omitted to avoid invalid engine references.");
            for(int index=0;index<planned.Length;index++)
            {
                ct.ThrowIfCancellationRequested();var tile=planned[index];progress?.Report($"Terrain {name}: {index+1}/{planned.Length} — LOD{(int)tile.Level} ({tile.X},{tile.Y})");
                GenerateTile(tile,source,null);
            }
            foreach (var (season, swaps) in seasons)
            {
                var seasonal = new TerrainSource(game,assets,world,grid,request.UseExistingTerrain,ct,swaps,season,defaultDiffuse,defaultNormal,request.Materials);
                foreach (var tile in planned)
                {
                    ct.ThrowIfCancellationRequested();
                    progress?.Report($"Terrain {name} {season}: LOD{(int)tile.Level} ({tile.X},{tile.Y})");
                    GenerateTile(tile,seasonal,season);
                }
                if (seasonal.FallbackUsed.Count>0) Warn($"{name} {season}: missing LAND uses installed seasonal terrain textures where present, otherwise the installed default terrain. Check these areas in game.");
                Collect(seasonal);
            }
            string? heightmap=null;
            if(request.ExportHeightmaps)
            {
                progress?.Report("Exporting terrain-shadow heightmap: "+name);
                int minX=planned.Min(t=>t.X),minY=planned.Min(t=>t.Y),maxX=planned.Max(t=>t.X+(int)t.Level)-1,maxY=planned.Max(t=>t.Y+(int)t.Level)-1;
                var export=Measure("terrain-heightmap",()=>TerrainHeightmap.Export(name,minX,minY,maxX,maxY,request.HeightmapMaximumSize,source.Height,ct));
                heightmap=export.Path;Write(heightmap,export.Bytes);
            }
            reports.Add(new(name,source.Cells.Count,source.FallbackUsed.Count,planned.Length*(1+seasons.Count),heightmap));
            if(source.FallbackUsed.Count>0)Warn($"{name}: sampled {source.FallbackUsed.Count} existing terrain tiles for missing LAND. Those areas retain the source terrain's detail.");
            Write(LodSettings.RelativePathFor(name),settings.ToBytes());
            Collect(source);
        }
        if(tiles.Count==0)throw new InvalidDataException("No terrain tiles were generated. Check worldspace selection, LOD settings and landscape coverage.");
        if(wanted is not null && wanted.Except(reports.Select(r=>r.Worldspace),StringComparer.OrdinalIgnoreCase).Any())
            throw new InvalidDataException("Not all explicitly selected worldspaces generated terrain. Review the warnings; previous output was preserved.");
        generation.Dispose();
        var materials = materialReports.OrderBy(m=>m.Source,StringComparer.Ordinal).ThenBy(m=>m.Diffuse,StringComparer.Ordinal).ToArray();
        var performance=new TerrainPerformance(built,reused,new Dictionary<string,double>(timings));
        progress?.Report($"Terrain tiles: {built} generated, {reused} restored from verified checkpoints; {timings.GetValueOrDefault("terrain-sampling"):F2}s sampling, {timings.GetValueOrDefault("terrain-encoding"):F2}s encoding.");
        var manifest=new {Version=1,ApplicationVersion=ProductInfo.Version,GeneratedAt=DateTimeOffset.UtcNow,Request=request,Worlds=reports,Tiles=tiles,Materials=materials,Performance=performance,Warnings=warnings,Files=owned.Files};
        Write(ManifestName,JsonSerializer.SerializeToUtf8Bytes(manifest,PersistentPipeline.Json));
        OutputSnapshot output;using(WorkTiming.Measure("output-verification"))output=OutputSnapshot.Capture(stage.Payload,progress,ct);
        stage.Commit(progress);
        return new(request.OutputFolder,reports,tiles,warnings,watch.Elapsed.TotalSeconds,stage.PreviousOutput,output,materials,performance);
        void Collect(TerrainSource source) { materialReports.UnionWith(source.MaterialReports); foreach(string warning in source.MaterialWarnings) if(!warnings.Contains(warning)) Warn(warning); }
        void Write(string relative,byte[] bytes) => Measure("terrain-writing",()=>
        {
            ct.ThrowIfCancellationRequested();using var timing=WorkTiming.Measure("file-write-worker");
            string path=GamePath.ToFileSystemPath(stage.Payload,relative);Directory.CreateDirectory(Path.GetDirectoryName(path)!);File.WriteAllBytes(path,bytes);
            owned.Files[Path.GetRelativePath(stage.Payload,path).Replace('\\','/')]=OutputSnapshot.HashFile(path,ct);return true;
        });
        T Measure<T>(string phase,Func<T> action)
        {
            using var timing=WorkTiming.Measure(phase);var timer=Stopwatch.StartNew();
            try {return action();}finally {timings[phase]=timings.GetValueOrDefault(phase)+timer.Elapsed.TotalSeconds;}
        }
        void GenerateTile(QuadKey tile,TerrainSource source,string? season)
        {
            string stem=$"{tile.Worldspace}.{(int)tile.Level}.{tile.X}.{tile.Y}"+(season is null?"":"."+season);
            string[] files=[$"meshes/terrain/{tile.Worldspace}/{stem}.btr",$"textures/terrain/{tile.Worldspace}/{stem}.dds",$"textures/terrain/{tile.Worldspace}/{stem}_n.dds"];
            var identity=new TerrainTileResult(tile.Worldspace,(int)tile.Level,tile.X,tile.Y,0,0,season);
            var saved=cache is null?null:Measure("terrain-cache-verification",()=>cache.Restore(identity,files,stage.Payload));
            if(saved is not null)
            {
                foreach(var file in saved.Output.Files)owned.Files[file.Key]=file.Value;
                source.RestoreFallbackTiles(saved.FallbackTiles);materialReports.UnionWith(saved.Materials);
                foreach(string warning in saved.Warnings)if(!warnings.Contains(warning))Warn(warning);
                tiles.Add(saved.Tile);reused++;
                progress?.Report($"Reused terrain tile {stem}: mesh and both textures verified.");return;
            }
            var mesh=Measure("terrain-mesh",()=>TerrainTileBuilder.Build(tile,source.Height,(x,y)=>request.Water&&source.HasLodWater?source.Water(x,y):null,request.SkirtDepth,ct,season));
            Write(files[0],mesh.Bytes);
            var (diffuse,normal)=Measure("terrain-sampling",()=>Bake(tile,source,request,ct));
            Write(files[1],Measure("terrain-encoding",()=>TextureImages.Encode(diffuse)));
            Write(files[2],Measure("terrain-encoding",()=>TextureImages.Encode(normal,normal:true)));
            var result=identity with {Triangles=mesh.Land.Indices.Length/3,WaterCells=mesh.WaterCells};
            if(cache is not null)Measure("terrain-cache-writing",()=>
            {
                cache.Store(new(result,new OutputSnapshot {Files=files.ToDictionary(f=>f,f=>owned.Files[f])},
                    source.FallbackUsed.ToArray(),source.MaterialReports.ToArray(),source.MaterialWarnings.ToArray()),stage.Payload);return true;
            });
            tiles.Add(result);built++;progress?.Report("Completed terrain tile "+stem);
        }

    }
    public static OutputSnapshot ReadManifest(string folder)
    {
        using var document = JsonDocument.Parse(File.ReadAllText(Path.Combine(folder, ManifestName)));
        var root = document.RootElement;
        if (root.GetProperty("Version").GetInt32() != 1) throw new InvalidDataException("Unsupported terrain manifest; regenerate terrain.");
        return new OutputSnapshot { Files = root.GetProperty("Files").Deserialize<Dictionary<string, string>>() ?? throw new InvalidDataException("Missing terrain files.") };
    }
    private static (TextureImage Diffuse,TextureImage Normal) Bake(QuadKey tile,TerrainSource source,TerrainGenerationRequest settings,CancellationToken ct)
    {
        float strength = (settings.Materials ?? new()).NormalStrength;
        int size=settings.TextureSize;var diffuse=TextureImages.Blank(size,size);var normal=TextureImages.Blank(size,size);
        float span=(int)tile.Level*4096f,footprint=span/size;
        for(int y=0;y<size;y++)
        {
            ct.ThrowIfCancellationRequested();
            for(int x=0;x<size;x++)
            {
                float wx=tile.X*4096f+(x+.5f)*footprint,wy=tile.Y*4096f+span-(y+.5f)*footprint;
                var sample=source.Surface(wx,wy,footprint,settings.TextureRepeatsPerCell,settings.VertexColorStrength);
                var color=sample.Color*settings.Brightness;
                int o=(y*size+x)*4;diffuse.Pixels[o]=TerrainSource.Srgb(color.X);diffuse.Pixels[o+1]=TerrainSource.Srgb(color.Y);diffuse.Pixels[o+2]=TerrainSource.Srgb(color.Z);diffuse.Pixels[o+3]=255;
                float h=source.Height(wx,wy)??throw new InvalidDataException("Missing height while baking terrain normals.");
                float step=Math.Max(128,footprint*.5f);
                float dx=((source.Height(wx+step,wy)??h)-(source.Height(wx-step,wy)??h))/(2*step);
                float dy=((source.Height(wx,wy+step)??h)-(source.Height(wx,wy-step)??h))/(2*step);
                var n=Vector3.Normalize(new Vector3(-dx,1,-dy)); // terrain convention: east, up, north
                n = sample.ExistingNormal is { } existing ? Vector3.Normalize(Vector3.Lerp(n,existing,Math.Min(1,strength))) : TerrainMaterials.Normal(n,sample.Detail,strength);
                normal.Pixels[o]=(byte)Math.Clamp(MathF.Round((n.X+1)*127.5f),0,255);normal.Pixels[o+1]=(byte)Math.Clamp(MathF.Round((n.Y+1)*127.5f),0,255);
                normal.Pixels[o+2]=(byte)Math.Clamp(MathF.Round((n.Z+1)*127.5f),0,255);normal.Pixels[o+3]=255;
            }
        }
        return(diffuse,normal);
    }
